#!/usr/bin/env python3
"""
Prepare the homepage hero from the user-supplied 3D Mahjong tile photo (white face, red 發, green right side).

  python3 scripts/prepare-hero.py /path/to/tile-photo.jpg

1. Crops tightly around the tile (the source has large white margins).
2. Removes ONLY the near-pure-white background connected to the image border (flood fill), keeping the
   tile's off-white face intact, with a 1px inset and soft feather so the edge is clean in light and dark mode.
3. Samples the brand green from well-lit, saturated mid-tones of the tile's green side (not the darkest shadow
   or white highlights) and writes it to app/globals.css (--brand) and lib/brand.ts.
4. Writes public/hero/mahjong-fa-tile.png and lib/hero.ts, plus preview images on light/dark backgrounds
   (scripts/hero-preview-*.png) for visual review. Nothing else in the app is changed.
"""
import colorsys, json, re, sys
from collections import deque
from pathlib import Path
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent

def main(src):
    im = Image.open(src).convert("RGB")
    w, h = im.size
    px = im.load()
    # --- 1. background mask: flood from the border through near-pure-white, low-saturation pixels only.
    # The tile's off-white face (lum ~150–240 in the supplied photo) is never reached, so it stays opaque.
    def is_bg(c):
        mn, mx = min(c), max(c)
        return mx - mn <= 12 and (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]) >= 246
    bg = bytearray(w * h)
    q = deque((x, y) for x in range(w) for y in (0, h - 1))
    q.extend((x, y) for y in range(h) for x in (0, w - 1))
    while q:
        x, y = q.popleft()
        i = y * w + x
        if bg[i] or not is_bg(px[x, y]): continue
        bg[i] = 1
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h and not bg[ny * w + nx]: q.append((nx, ny))
    # --- 2. bounding box of the non-background (tile + shadow)
    xs = [i % w for i in range(w * h) if not bg[i]]
    ys = [i // w for i in range(w * h) if not bg[i]]
    if not xs: sys.exit("Could not find the tile — is the background white?")
    pad = int(0.04 * max(w, h))
    x0, y0, x1, y1 = max(0, min(xs) - pad), max(0, min(ys) - pad), min(w, max(xs) + pad), min(h, max(ys) + pad)
    out = Image.new("RGBA", (x1 - x0, y1 - y0))
    op = out.load()
    for y in range(y0, y1):
        for x in range(x0, x1):
            r, g, b = px[x, y]
            op[x - x0, y - y0] = (r, g, b, 0 if bg[y * w + x] else 255)
    # pull the edge in by 1px (drops white JPEG fringe), then feather slightly so it looks clean on dark backgrounds
    alpha = out.getchannel("A").filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.8))
    out.putalpha(alpha)
    # --- 3. sample brand green from the tile's green side
    greens = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            if bg[y * w + x]: continue
            r, g, b = px[x, y]
            if g > r + 20 and g > b + 10:
                hh, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
                greens.append((v, s, (r, g, b)))
    if len(greens) < 50: sys.exit("Not enough green pixels found on the tile side to sample a color.")
    greens.sort()
    lo, hi = int(len(greens) * 0.45), int(len(greens) * 0.80)   # well-lit mid-tones, excluding deep shadow and highlights
    mid = sorted(greens[lo:hi], key=lambda t: -t[1])[: max(20, (hi - lo) // 3)]  # most saturated of those
    rs, gs, bs = zip(*[c for _, _, c in mid])
    med = lambda a: sorted(a)[len(a) // 2]
    hexv = "#%02X%02X%02X" % (med(rs), med(gs), med(bs))
    # --- 4. write assets and tokens
    (ROOT / "public/hero").mkdir(parents=True, exist_ok=True)
    target = 520  # px on the long side (≈2× for a ~240px display)
    scale = target / max(out.size)
    out = out.resize((round(out.width * scale), round(out.height * scale)), Image.LANCZOS)
    out.save(ROOT / "public/hero/mahjong-fa-tile.png", optimize=True)
    src = "/hero/mahjong-fa-tile.png"
    try:
        out.save(ROOT / "public/hero/mahjong-fa-tile.webp", quality=90, method=6)
        src = "/hero/mahjong-fa-tile.webp"  # ~5× smaller, keeps transparency
    except Exception: pass
    (ROOT / "lib/hero.ts").write_text(
        "/** Homepage-only hero artwork (user-supplied 3D 發 tile). Generated by scripts/prepare-hero.py. */\n"
        f'export const HERO: {{ src: string; width: number; height: number; alt: string }} | null = {json.dumps({"src": src, "width": out.width, "height": out.height, "alt": ""})};\n')
    css = ROOT / "app/globals.css"
    css.write_text(re.sub(r"--brand: #[0-9a-fA-F]{6};", f"--brand: {hexv.lower()};", css.read_text(), count=1))
    br = ROOT / "lib/brand.ts"
    br.write_text(re.sub(r'BRAND_GREEN = "#[0-9A-Fa-f]{6}"', f'BRAND_GREEN = "{hexv}"', br.read_text()))
    for name, color in (("light", (255, 255, 255)), ("dark", (0, 0, 0))):
        prev = Image.new("RGBA", (out.width + 80, out.height + 80), color + (255,))
        prev.alpha_composite(out, (40, 40))
        sw = Image.new("RGBA", (60, 60), tuple(int(hexv[i:i + 2], 16) for i in (1, 3, 5)) + (255,))
        prev.alpha_composite(sw, (10, 10))
        prev.convert("RGB").save(ROOT / f"scripts/hero-preview-{name}.png")
    print(f"Brand green sampled from tile side: {hexv} (from {len(greens)} green pixels)")
    print(f"Hero written: public/hero/mahjong-fa-tile.png ({out.width}×{out.height})")

if __name__ == "__main__":
    if len(sys.argv) != 2: sys.exit(__doc__)
    main(sys.argv[1])
